CREATE TABLE roles (
 id_rol BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(30) NOT NULL UNIQUE CHECK (nombre IN ('CLIENTE','EMPLEADO','ADMINISTRADOR')),
 descripcion VARCHAR(150)
);
CREATE TABLE usuarios (
 id_usuario UUID PRIMARY KEY, id_rol BIGINT NOT NULL REFERENCES roles,
 nombre VARCHAR(80) NOT NULL, apellido VARCHAR(80), correo VARCHAR(150) NOT NULL,
 password_hash VARCHAR(255) NOT NULL, estado BOOLEAN NOT NULL DEFAULT TRUE,
 fecha_creacion TIMESTAMPTZ, fecha_actualizacion TIMESTAMPTZ,
 datos_legado JSONB CHECK (datos_legado IS NULL OR jsonb_typeof(datos_legado)='object')
);
CREATE UNIQUE INDEX usuarios_correo_unico ON usuarios (lower(btrim(correo)));
CREATE INDEX usuarios_rol_idx ON usuarios(id_rol);
CREATE TABLE perfil_cliente (
 id_perfil UUID PRIMARY KEY, id_usuario UUID NOT NULL UNIQUE REFERENCES usuarios,
 telefono VARCHAR(20), fecha_nacimiento DATE, observaciones TEXT,
 autoriza_contexto_ia BOOLEAN, fecha_actualizacion TIMESTAMPTZ,
 datos_legado JSONB CHECK (datos_legado IS NULL OR jsonb_typeof(datos_legado)='object')
);
CREATE TABLE preferencias_cliente (
 id_preferencia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_usuario UUID NOT NULL REFERENCES usuarios, tipo VARCHAR(40) NOT NULL,
 descripcion TEXT NOT NULL, activa BOOLEAN NOT NULL DEFAULT TRUE,
 fecha_creacion TIMESTAMPTZ, version_cifrado SMALLINT CHECK(version_cifrado=2)
);
CREATE INDEX preferencias_usuario_idx ON preferencias_cliente(id_usuario);
CREATE TABLE categorias (
 id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(80) NOT NULL UNIQUE, descripcion VARCHAR(250),
 estado BOOLEAN NOT NULL DEFAULT TRUE, fecha_creacion TIMESTAMPTZ
);
CREATE TABLE productos (
 id_producto UUID PRIMARY KEY, id_categoria BIGINT NOT NULL REFERENCES categorias,
 nombre VARCHAR(120) NOT NULL, descripcion TEXT,
 precio NUMERIC(10,2) CHECK(precio>0 AND precio<>'NaN'::numeric), stock_minimo INTEGER CHECK(stock_minimo>=0),
 imagen_url VARCHAR(500), estado BOOLEAN NOT NULL DEFAULT FALSE,
 fecha_creacion TIMESTAMPTZ, fecha_actualizacion TIMESTAMPTZ,
 valores_nutricionales TEXT,
 datos_legado JSONB CHECK(datos_legado IS NULL OR jsonb_typeof(datos_legado)='object'),
 CHECK(NOT estado OR precio IS NOT NULL)
);
CREATE INDEX productos_categoria_idx ON productos(id_categoria);
CREATE TABLE ingredientes (
 id_ingrediente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(100) NOT NULL UNIQUE, descripcion VARCHAR(250)
);
CREATE TABLE producto_ingrediente (
 id_producto UUID NOT NULL REFERENCES productos,
 id_ingrediente BIGINT NOT NULL REFERENCES ingredientes,
 cantidad_descriptiva VARCHAR(100), PRIMARY KEY(id_producto,id_ingrediente)
);
CREATE INDEX producto_ingrediente_ingrediente_idx ON producto_ingrediente(id_ingrediente);
CREATE TABLE inventario (
 id_inventario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_producto UUID NOT NULL UNIQUE REFERENCES productos,
 cantidad INTEGER NOT NULL CHECK(cantidad>=0), fecha_actualizacion TIMESTAMPTZ
);
CREATE TABLE movimientos_inventario (
 id_movimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_producto UUID NOT NULL REFERENCES productos, id_usuario UUID NOT NULL REFERENCES usuarios,
 tipo VARCHAR(20) NOT NULL CHECK(tipo IN ('ENTRADA','SALIDA','AJUSTE')),
 cantidad INTEGER NOT NULL CHECK(cantidad>0), motivo VARCHAR(250), fecha TIMESTAMPTZ
);
CREATE INDEX movimientos_producto_idx ON movimientos_inventario(id_producto);
CREATE INDEX movimientos_usuario_idx ON movimientos_inventario(id_usuario);
CREATE TABLE pedidos (
 id_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_cliente UUID NOT NULL REFERENCES usuarios,
 estado VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE'
 CHECK(estado IN ('PENDIENTE','CONFIRMADO','EN_PREPARACION','LISTO','ENTREGADO','CANCELADO')),
 subtotal NUMERIC(10,2) NOT NULL CHECK(subtotal>=0 AND subtotal<>'NaN'::numeric), total NUMERIC(10,2) NOT NULL CHECK(total>=0 AND total<>'NaN'::numeric),
 fecha_pedido TIMESTAMPTZ, fecha_actualizacion TIMESTAMPTZ
);
CREATE INDEX pedidos_cliente_estado_idx ON pedidos(id_cliente,estado);
CREATE TABLE detalle_pedido (
 id_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_pedido BIGINT NOT NULL REFERENCES pedidos, id_producto UUID NOT NULL REFERENCES productos,
 cantidad INTEGER NOT NULL CHECK(cantidad>0), precio_unitario NUMERIC(10,2) NOT NULL CHECK(precio_unitario>0 AND precio_unitario<>'NaN'::numeric),
 subtotal NUMERIC(10,2) NOT NULL CHECK(subtotal>=0 AND subtotal<>'NaN'::numeric)
);
CREATE INDEX detalle_pedido_pedido_idx ON detalle_pedido(id_pedido);
CREATE INDEX detalle_pedido_producto_idx ON detalle_pedido(id_producto);
CREATE TABLE conversaciones_ia (
 id_conversacion UUID PRIMARY KEY, id_usuario UUID NOT NULL REFERENCES usuarios,
 titulo VARCHAR(150), fecha_inicio TIMESTAMPTZ, fecha_actualizacion TIMESTAMPTZ,
 estado VARCHAR(30) NOT NULL CHECK(estado IN ('PENDIENTE','RESPONDIDA','ERROR')),
 revisada BOOLEAN, id_interaccion_origen UUID UNIQUE,
 datos_legado JSONB CHECK(datos_legado IS NULL OR jsonb_typeof(datos_legado)='object')
);
CREATE INDEX conversaciones_usuario_fecha_idx ON conversaciones_ia(id_usuario,fecha_inicio DESC);
CREATE TABLE mensajes_ia (
 id_mensaje BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_conversacion UUID NOT NULL REFERENCES conversaciones_ia,
 tipo VARCHAR(20) NOT NULL CHECK(tipo IN ('USUARIO','ASISTENTE','SISTEMA')),
 contenido TEXT NOT NULL, fecha TIMESTAMPTZ, version_cifrado SMALLINT NOT NULL CHECK(version_cifrado=2)
);
CREATE INDEX mensajes_conversacion_fecha_idx ON mensajes_ia(id_conversacion,fecha,id_mensaje);
CREATE TABLE auditoria (
 id_auditoria UUID PRIMARY KEY, id_usuario UUID NOT NULL REFERENCES usuarios,
 accion VARCHAR(80) NOT NULL, entidad VARCHAR(80), id_entidad TEXT,
 recurso_accedido TEXT, datos_anteriores JSONB, datos_nuevos JSONB, ip VARCHAR(45), fecha TIMESTAMPTZ
);
CREATE INDEX auditoria_usuario_fecha_idx ON auditoria(id_usuario,fecha DESC);
CREATE TABLE errores_sistema (
 id_error BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_usuario UUID REFERENCES usuarios, servicio VARCHAR(60) NOT NULL,
 codigo VARCHAR(50) NOT NULL, mensaje VARCHAR(250) NOT NULL, detalle TEXT, fecha TIMESTAMPTZ
);
CREATE INDEX errores_usuario_fecha_idx ON errores_sistema(id_usuario,fecha DESC);
-- La cardinalidad mínima se comprueba al confirmar, permitiendo insertar padre e hijos juntos.
CREATE FUNCTION comprobar_detalle_pedido() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE destino BIGINT;
BEGIN
 destino := CASE WHEN TG_TABLE_NAME='pedidos' THEN NEW.id_pedido
                 WHEN TG_OP='DELETE' THEN OLD.id_pedido ELSE NEW.id_pedido END;
 IF EXISTS(SELECT 1 FROM pedidos WHERE id_pedido=destino)
 AND NOT EXISTS(SELECT 1 FROM detalle_pedido WHERE id_pedido=destino) THEN
  RAISE EXCEPTION 'Pedido sin detalles' USING ERRCODE='23514';
 END IF;
 IF TG_OP='UPDATE' AND TG_TABLE_NAME='detalle_pedido' THEN
  IF EXISTS(SELECT 1 FROM pedidos WHERE id_pedido=OLD.id_pedido)
  AND NOT EXISTS(SELECT 1 FROM detalle_pedido WHERE id_pedido=OLD.id_pedido) THEN
   RAISE EXCEPTION 'Pedido sin detalles' USING ERRCODE='23514';
  END IF;
 END IF;
 RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER pedido_con_detalle AFTER INSERT OR UPDATE ON pedidos
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION comprobar_detalle_pedido();
CREATE CONSTRAINT TRIGGER detalle_no_vacio AFTER DELETE OR UPDATE ON detalle_pedido
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION comprobar_detalle_pedido();
CREATE FUNCTION comprobar_mensajes() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE destino UUID;
BEGIN
 destino := CASE WHEN TG_OP='DELETE' THEN OLD.id_conversacion ELSE NEW.id_conversacion END;
 IF EXISTS(SELECT 1 FROM conversaciones_ia WHERE id_conversacion=destino)
 AND NOT EXISTS(SELECT 1 FROM mensajes_ia WHERE id_conversacion=destino) THEN
  RAISE EXCEPTION 'Conversacion sin mensajes' USING ERRCODE='23514';
 END IF;
 IF TG_OP='UPDATE' AND TG_TABLE_NAME='mensajes_ia' THEN
  IF EXISTS(SELECT 1 FROM conversaciones_ia WHERE id_conversacion=OLD.id_conversacion)
  AND NOT EXISTS(SELECT 1 FROM mensajes_ia WHERE id_conversacion=OLD.id_conversacion) THEN
   RAISE EXCEPTION 'Conversacion sin mensajes' USING ERRCODE='23514';
  END IF;
 END IF;
 RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER conversacion_con_mensaje AFTER INSERT OR UPDATE ON conversaciones_ia
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION comprobar_mensajes();
CREATE CONSTRAINT TRIGGER mensaje_no_vacio AFTER DELETE OR UPDATE ON mensajes_ia
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION comprobar_mensajes();
